"""Authors for the Research section: who wrote or shared each public entry, and a
reputation score per author. Imported by build.py.

Credits come from each entry's `by` line:
  * names in authors.json `people` (with aliases) found outside parentheses,
  * "X's post / article / review", "shared by X", "via X", "analysis by X" ...,
  * a `by` line that is only a name ("Gunnar Morling", "A and B").
Paper author lists ("Zhang, Gao, Zhao et al.") are not credited. authors.json
`overrides` replaces the parse for one entry, and `ignore` drops false matches.

Reputation = sum over an author's entries of an entry quality score (see
QUALITY below), times TRUSTED_BOOST when the author is on the trusted-author
list. Only public entries (those in entries.json) are ever counted.
"""
import json, re, unicodedata
from pathlib import Path

SRC = Path(__file__).resolve().parent
PROJECT = Path("/mnt/project-files/research")  # present in the publish job; absent elsewhere

# Entry quality. Base 1 per public entry, then:
QUALITY = {
    "base": 1.0,
    "review_first_pass": 0.25,   # passed the Reviewer on the first round
    "review_revise": -0.25,      # Reviewer currently asks for a revision
    "in_guide": 0.5,             # cited by at least one published field guide
}
TRUSTED_BOOST = 1.25

SHARED_WORDS = r"(?:shared|surfaced|reshared|resharing|announced|analysis|summary|coverage|resurfaced|curated)\s+by"
NAME = r"[A-Z][\w.\-’'éèáíóúöüçÁÉÓÖÜØø]*(?:\s+(?:van|de|der|von|da|di|del|A\.)?\s*[A-Z][\w.\-éèáíóúöüçøØ]*){0,3}"


def slugify(s):
    s = unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode()
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def load_cfg():
    p = SRC / "authors.json"
    return json.loads(p.read_text()) if p.exists() else {"people": {}, "overrides": {}, "ignore": []}


def refresh_quality_snapshot(public_ids):
    """Copy the public-safe parts of the pipeline (review verdicts, trusted names)
    into _src/quality.json so builds without the project folder still work."""
    out = SRC / "quality.json"
    if not PROJECT.exists():
        return json.loads(out.read_text()) if out.exists() else {"reviews": {}, "trusted": []}
    reviews = {}
    for f in sorted((PROJECT / "pipeline" / "reviews").glob("R[0-9][0-9][0-9]*.json")):
        try:
            d = json.loads(f.read_text())
        except Exception:
            continue
        rid = d.get("r") or f.stem
        if rid not in public_ids:
            continue
        reviews[rid] = {"verdict": d.get("verdict"), "round": d.get("round", 1)}
    trusted = []
    tl = PROJECT / "linkedin-trusted-authors.md"
    if tl.exists():
        for line in tl.read_text().splitlines():
            m = re.match(r"-\s+(.+)", line.strip())
            if not m:
                continue
            name = re.sub(r"\s*\(.*?\)", "", m.group(1)).strip()
            trusted += [n.strip() for n in re.split(r"\s*/\s*|,\s*", name) if n.strip()]
    snap = {"about": "Generated by authors.py from the research pipeline: Reviewer verdicts per entry and the trusted-author names. No review notes.",
            "reviews": reviews, "trusted": trusted}
    out.write_text(json.dumps(snap, indent=1, ensure_ascii=False) + "\n")
    return snap


def _split_names(s):
    s = re.sub(r"\b(?:the|his|her|their)\s+", "", s)
    parts = re.split(r",\s*|\s+and\s+|\s*&\s*", s)
    return [p.strip(" .") for p in parts if p.strip(" .")]


def parse_by(by, cfg):
    """Return [(display name, role)] for one `by` line. role: 'author' or 'shared'."""
    people = cfg["people"]
    alias = {}
    for slug, p in people.items():
        for a in p.get("match") or [p["name"], *p.get("aliases", [])]:
            alias[a] = slug
    bare = re.sub(r"\([^)]*\)", "", by)
    found = []

    def add(name, role):
        name = name.strip(" .,;:")
        if not name:
            return
        found.append((name, role))

    # shared-by clauses ("shared by X and Y", "via X's post")
    shared_spans = []
    for rx in (SHARED_WORDS + r"\s+(.+?)(?:;|$|, \d{4}|, resharing|['’]s\b)", r"\bvia\s+(.+?)(?:;|$|['’]s\b|, \d{4})"):
        for m in re.finditer(rx, bare):
            shared_spans.append(m.span())
            for n in _split_names(m.group(1)):
                add(n, "shared")
    in_shared = lambda i: any(a <= i < b for a, b in shared_spans)
    # possessives: "X's post", "X's and Y's posts"
    for m in re.finditer(r"(" + NAME + r")['’]s?\b", bare):
        if m.group(0).endswith(("'s", "’s")) and not in_shared(m.start()):
            add(m.group(1), "author")
    # known names (case-sensitive, longest first, each span used once)
    masked = bare
    for a, slug in sorted(alias.items(), key=lambda kv: -len(kv[0])):
        for m in list(re.finditer(r"(?<![\w./-])" + re.escape(a) + r"(?![\w/-])", masked)):
            add(people[slug]["name"], "shared" if in_shared(m.start()) else "author")
        masked = re.sub(r"(?<![\w./-])" + re.escape(a) + r"(?![\w/-])", lambda m: "#" * len(m.group(0)), masked)
    # leading run of plain names: "Gunnar Morling", "Kaden Zheng and Pratyusha Sharma", "David Mezzetti, NeuML, ..."
    head = re.split(r";|\s+(?:on|plus|with)\s+", bare)[0]
    if "et al" not in head:
        for n in _split_names(head):
            if re.fullmatch(NAME, n) and 2 <= len(n.split()) <= 4:
                add(n, "author")
            else:
                break
    return found


def resolve(found, cfg):
    """Map raw names to author slugs; drop ignored names and paper-list noise."""
    people = cfg["people"]
    alias = {}
    for slug, p in people.items():
        for a in p.get("match") or [p["name"], *p.get("aliases", [])]:
            alias[a] = slug
    ignore = {x.lower() for x in cfg.get("ignore", [])}
    out = {}
    for name, role in found:
        if name.lower() in ignore:
            continue
        slug = alias.get(name)
        if not slug:
            if not re.fullmatch(NAME, name) or len(name.split()) < 2 or len(name) > 40:
                continue
            slug = slugify(name)
        # 'author' wins over 'shared' when both appear
        if out.get(slug) != "author":
            out[slug] = role
    return out


def credits(entries, cfg):
    """{entry id: {author slug: role}} for public entries."""
    res = {}
    for rid, x in entries.items():
        if rid in cfg.get("overrides", {}):
            res[rid] = {o["who"]: o.get("role", "author") for o in cfg["overrides"][rid]}
        else:
            res[rid] = resolve(parse_by(x.get("by", ""), cfg), cfg)
    return res


def entry_quality(rid, snap, guide_of):
    q = QUALITY["base"]
    r = snap["reviews"].get(rid)
    parts = []
    if r:
        if r["verdict"] == "pass" and r.get("round", 1) == 1:
            q += QUALITY["review_first_pass"]; parts.append("first-round review pass")
        elif r["verdict"] in ("revise", "block"):
            q += QUALITY["review_revise"]; parts.append("review asked for revision")
    if guide_of.get(rid):
        q += QUALITY["in_guide"]; parts.append("cited in a field guide")
    return q, parts


def build_authors(entries, guides, theme_of, sub_of):
    """Return (authors list sorted by reputation, credits map)."""
    cfg = load_cfg()
    snap = refresh_quality_snapshot(set(entries))
    trusted = {t.lower() for t in snap.get("trusted", [])}
    cred = credits(entries, cfg)
    guide_of = {}
    for g in guides:
        for rid in g["entries"]:
            guide_of.setdefault(rid, []).append(g)
    names = {}
    for rid, m in cred.items():
        for slug in m:
            names.setdefault(slug, set())
    people = cfg["people"]
    # display names for auto-detected people come from the first raw match
    raw_name = {}
    for rid, x in entries.items():
        for name, _ in parse_by(x.get("by", ""), cfg):
            raw_name.setdefault(slugify(name), name)
    authors = []
    for slug in names:
        p = people.get(slug, {})
        name = p.get("name") or raw_name.get(slug) or slug
        rids = sorted((rid for rid, m in cred.items() if slug in m), reverse=True)
        if not rids:
            continue
        rows, score, n_first, n_reviewed = [], 0.0, 0, 0
        for rid in rids:
            q, why = entry_quality(rid, snap, guide_of)
            score += q
            r = snap["reviews"].get(rid)
            if r:
                n_reviewed += 1
                n_first += r["verdict"] == "pass" and r.get("round", 1) == 1
            rows.append(dict(id=rid, role=cred[rid][slug], q=q, why=why))
        is_trusted = any(a.lower() in trusted for a in [name, *p.get("aliases", [])])
        if is_trusted:
            score *= TRUSTED_BOOST
        gcount = {}
        for rid in rids:
            for g in guide_of.get(rid, []):
                gcount[g["slug"]] = gcount.get(g["slug"], 0) + 1
        subs = {}
        for rid in rids:
            s = sub_of[rid]
            subs[(s["n"], s["title"])] = subs.get((s["n"], s["title"]), 0) + 1
        top_subs = sorted(subs.items(), key=lambda kv: (-kv[1], kv[0][0]))[:3]
        tagc = {}
        for rid in rids:
            for t in entries[rid]["tags"]:
                tagc[t] = tagc.get(t, 0) + 1
        authors.append(dict(
            slug=slug, name=name, kind=p.get("kind", "person"), specialty=p.get("specialty", ""),
            url=p.get("url", ""), entries=rows, score=round(score, 2), trusted=is_trusted,
            reviewed=n_reviewed, first_pass=n_first,
            guides=[g for g in guides if g["slug"] in gcount], guide_count=gcount,
            top_subs=top_subs, top_tags=[t for t, _ in sorted(tagc.items(), key=lambda kv: (-kv[1], kv[0]))[:5]],
        ))
    authors.sort(key=lambda a: (-a["score"], -len(a["entries"]), a["name"].lower()))
    for i, a in enumerate(authors, 1):
        a["rank"] = i
    return authors, cred
